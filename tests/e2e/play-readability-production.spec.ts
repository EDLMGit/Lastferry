import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync, readFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { act, activate, idle, undo, fullyVisible } from './ui';
import { reviewDir } from './evidence';

test('production UI rescue, tide and terminal Undo with no development API', async ({ browser }) => {
  const origin = process.env.LAST_FERRY_PRODUCTION_URL ?? 'http://127.0.0.1:5284';
  const ctx = await browser.newContext({ viewport:{width:844,height:390},deviceScaleFactor:1,hasTouch:true });
  const page=await ctx.newPage();
  page.setDefaultTimeout(15000);
  const shot=async(name:string)=>{ const cdp=await ctx.newCDPSession(page); const capture=await cdp.send('Page.captureScreenshot',{format:'png',fromSurface:true}); const bytes=Buffer.from(capture.data,'base64'); writeFileSync(`${reviewDir}/${name}.png`,bytes); await cdp.detach(); expect(bytes.length).toBeGreaterThan(5000); };
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  mkdirSync(reviewDir,{recursive:true});
  await page.goto(origin+'/?cove=holding-pier');
  await expect(page.locator('#unload')).toBeVisible();
  expect(await page.evaluate(()=>!!(window as any).__LAST_FERRY__)).toBe(false);
  await act(page,'unload',true);
  await act(page,'map-shallows',true);
  await expect(page.locator('[data-testid=turn]')).toHaveText('02');
  await act(page,'map-rabbit-pier',true);
  await activate(page,'board',true);
  for(const button of await page.locator('.passenger-options button').all()) await fullyVisible(page,button);
  await fullyVisible(page,page.locator('#commit'));
  await expect(page.locator('#preview')).toContainText('The tide rises after this action');
  await expect(page.locator('.passenger-options button[aria-pressed="true"]')).toHaveCount(2);
  await shot('844x390-production-boarding');
  await activate(page,'commit',true);
  await idle(page);
  await expect(page.locator('[data-testid=tide]')).toHaveText('1');
  await undo(page,true);
  await expect(page.locator('[data-testid=tide]')).toHaveText('0');
  await act(page,'board',true);
  await act(page,'map-shallows',true);
  await act(page,'map-stone',true);
  await act(page,'board',true);
  await act(page,'map-harbor',true);
  await act(page,'unload',true);
  await expect(page.locator('#dialog')).toHaveAttribute('data-outcome','won');
  await expect(page.locator('[data-testid=turn]')).toHaveText('09');
  await undo(page,true);
  await expect(page.locator('[data-testid=turn]')).toHaveText('08');
  await act(page,'unload',true);
  await expect(page.locator('#dialog')).toHaveAttribute('data-outcome','won');
  await shot('844x390-production-arrival');
  expect(errors).toEqual([]);
  const files = ['dist/index.html',...readdirSync('dist/assets').map(p=>'dist/assets/'+p)];
  writeFileSync(`${reviewDir}/production.json`,JSON.stringify({origin,browser:browser.version(),viewport:page.viewportSize(),errors,productionApiAbsent:true,files:Object.fromEntries(files.map(p=>[p,createHash('sha256').update(readFileSync(p)).digest('hex')]))},null,2));
  await ctx.close();
});
