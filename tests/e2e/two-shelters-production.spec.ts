import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { act, activate, idle, undo } from './ui';
import { reviewDir, productionURL } from './evidence';

test('production Two Shelters rescue and tide Undo without development globals', async ({ browser }) => {
  const origin = process.env.LAST_FERRY_PRODUCTION_URL ?? productionURL;
  const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true });
  const page = await ctx.newPage();
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(origin+'/?cove=two-shelters');
  await expect(page.locator('#unload')).toBeVisible();
  expect(await page.evaluate(() => !!(window as any).__LAST_FERRY__)).toBe(false);
  await act(page,'unload',true);
  await act(page,'map-reeds',true);
  await act(page,'board',true);
  await act(page,'wait',true);
  await expect(page.locator('[data-testid=tide]')).toHaveText('1');
  await undo(page,true);
  await expect(page.locator('[data-testid=tide]')).toHaveText('0');
  await act(page,'wait',true);
  await act(page,'map-low',true);
  await act(page,'map-harbor',true);
  await act(page,'unload',true);
  await act(page,'map-low',true);
  await activate(page,'board',true);
  await expect(page.locator('.passenger-options button[aria-pressed=true]')).toHaveCount(2);
  await activate(page,'commit',true);
  await idle(page);
  await expect(page.locator('[data-testid=tide]')).toHaveText('2');
  await act(page,'map-harbor',true);
  if ((await page.locator('#view-toggle').textContent())?.includes('Play view')) await activate(page,'view-toggle',true);
  await act(page,'unload',true);
  await expect(page.locator('#dialog')).toHaveAttribute('data-outcome','won');
  await expect(page.locator('[data-testid=turn]')).toHaveText('11');
  await undo(page,true);
  await expect(page.locator('[data-testid=turn]')).toHaveText('10');
  await act(page,'unload',true);
  await expect(page.locator('#dialog')).toHaveAttribute('data-outcome','won');
  expect(errors).toEqual([]);
  mkdirSync(reviewDir,{recursive:true});
  await page.screenshot({path:`${reviewDir}/844x390-production-rescue.png`});
  const paths=['dist/index.html',...readdirSync('dist/assets').map(p=>'dist/assets/'+p)];
  writeFileSync(`${reviewDir}/production-candidate.json`,JSON.stringify({origin,browser:browser.version(),viewport:page.viewportSize(),errors,productionApiAbsent:true,files:Object.fromEntries(paths.map(p=>[p,createHash('sha256').update(readFileSync(p)).digest('hex')]))},null,2));
  await ctx.close();
});
